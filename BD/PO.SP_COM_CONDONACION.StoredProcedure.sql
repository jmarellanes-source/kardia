							UPDATE PO.SAF_MOV_ABONO SET CONCEPTO = REPLACE(CONCEPTO, IIF(CONCEPTO LIKE '%CONDONACION%', 'CONDONACION ', 'BONIFICACION '), 'PAGO CCO ') --COBB
							WHERE ID = @ID_UNICO
						END
						SET  @ORDEN = 0

