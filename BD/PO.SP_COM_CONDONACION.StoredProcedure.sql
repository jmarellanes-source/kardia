					IF @BANDERA = 0 BEGIN
						IF @SUMA89<@TOTAL --AND @SUMA89 > 0 -- SEGUNDA CONDICION ESTABA COMENTADA 
						BEGIN
							SELECT @ORDEN = @TOTAL - @SUMA89, @BANDERA = 1
							IF @ORDEN != 0 BEGIN

