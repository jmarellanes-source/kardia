CREATE PROCEDURE [PO].[SP_COM_REESTRCTURA_SN_CAP]
(
	@FECHA_INICIO DATE
)
AS
BEGIN
    SET NOCOUNT ON

    declare @ID_POLIZA int = 56
			,@FECHA_ANT date
    
    set @FECHA_ANT = DATEADD(day, -1, @FECHA_INICIO)
	
	BEGIN TRY
		BEGIN TRANSACTION
	
		DELETE FROM PO.SAF_MOV_ABONO WHERE FECHA_MOVIMIENTO = @FECHA_INICIO AND ID_POLIZA = @ID_POLIZA

		-- ====== REESTRUCTURA DESDE MODULO DE SAF ============
	
        -- Credito anterior vs Reestructuras - realizadas desde modulo de reestructuras
        SELECT C.NUM_CREDITO, C.MON_CREDITO, C.COD_EMPRESA, C.NUM_DESC_TIPO_CREDITO, P.Mon_movimiento
			, dbo.FN_CREDITO_PREVIO(C.NUM_CREDITO) AS NUM_CREDITO_ANT
        INTO #REESTRUCTURAS
        FROM Quiero_Confianza_shadow.PR.PR_CREDITOS C
			INNER JOIN Quiero_Confianza_shadow.PR.PR_ENCABEZADO_PAGO P ON C.NUM_CREDITO=P.Num_credito
        WHERE C.IND_ESTADO_CRED = 'E' AND C.FEC_APERTURA = @FECHA_INICIO
			AND P.Tip_transaccion = 3 AND P.Fec_movimiento= @FECHA_INICIO
			AND C.NUM_DESC_TIPO_CREDITO IN (5,   12,13,14,15,28,   2,18,27)

        -- Credito anterior vs Reestructuras - realizadas por cancelacion y alta
        INSERT INTO #REESTRUCTURAS
        SELECT C.NUM_CREDITO, C.MON_CREDITO, C.COD_EMPRESA, C.NUM_DESC_TIPO_CREDITO, P.Mon_movimiento
			, dbo.FN_CREDITO_PREVIO_ID(C.ID_EXTERNO,C.NUM_CREDITO,C.COD_CLIENTE,@FECHA_INICIO) AS NUM_CREDITO_ANT
        FROM Quiero_Confianza_shadow.PR.PR_CREDITOS C
			INNER JOIN Quiero_Confianza_shadow.PR.PR_ENCABEZADO_PAGO P ON C.NUM_CREDITO=P.Num_credito
        WHERE C.IND_ESTADO_CRED != 'E' AND cast(C.FEC_APERTURA AS DATE) = @FECHA_INICIO
			AND P.Tip_transaccion = 3 AND cast(P.Fec_movimiento AS DATE) = @FECHA_INICIO
			AND C.NUM_DESC_TIPO_CREDITO IN (5,   12,13,14,15,28,   2,18,27)
			AND C.ID_EXTERNO like 'R%'

		-- Se obtienen reestructuras sin capitalizacion
		SELECT C.NUM_CREDITO_ANT
		INTO #CREDITOS_REESTRUCTURA
		FROM Quiero_Confianza_shadow.PR.PR_ENCABEZADO_PAGO A
		    INNER JOIN Quiero_Confianza_shadow.PR.PR_DETALLE_PAGO B ON A.ID_SECUENCIA = B.ID_SECUENCIA
		    INNER JOIN #REESTRUCTURAS C ON A.COD_EMPRESA = C.COD_EMPRESA AND A.NUM_CREDITO = C.NUM_CREDITO_ANT
		WHERE A.Fec_movimiento = @FECHA_INICIO
			AND B.MON_PAGO <> 0
			AND C.Mon_movimiento = B.MON_PAGO
			AND COD_CONCEPTO = 'PRINCIPAL'
			AND A.ID_CUENTA IN ('140103009001','140103009002','140103009003')
		GROUP BY C.NUM_CREDITO_ANT
		

		INSERT INTO PO.SAF_MOV_ABONO(
			ID_EXTERNO, NUM_CREDITO, NOM_CLIENTE, CUENTA_CARGO, CUENTA_ABONO, ID_PRODUCTO, NOMBRE_PRODUCTO, ID_FONDEO, RUBRO, MONTO
			,MON_PAGO_IVA, IND_FORMA_PAGO, ID_TIPO_CREDITO, TIPO_CREDITO, IND_ESTADO, CARTERA_VENCIDA, FECHA_MOVIMIENTO
			,TIP_TRANSACCION, SUBTIP_TRANSAC, IND_ETAPA, MON_CREDITO, CEDIDO, FEC_APERTURA, ID_SECUENCIA, ID_REFERENCIA, ID_CUENTA, IND_COVID, 
			CONCEPTO_FINAL, APELLIDO, TABLA_ORIGEN, ID_POLIZA, TIPO_VIVIENDA, REVERSO, CANAL)
		SELECT C.ID_EXTERNO
			,C.NUM_CREDITO
			,dbo.FN_FORMA_NOMBRE(PF.PRIMER_APELLIDO, PF.SEGUNDO_APELLIDO, PF.PRIMER_NOMBRE, PF.SEGUNDO_NOMBRE, PJ.RAZON_SOCIAL, PJ.NOM_COMERCIAL)
			,'' AS CUENTA_CARGO
			,'' AS CUENTA_ABONO
			,ISNULL((SELECT TOP 1 NUM_PRODUCTO FROM PO.PR_CAT_PRODUCTO WHERE ID_SAF = P.TIP_CREDITO), P.TIP_CREDITO) ID_PRODUCTO
			,CP.NOMBRE_CORTO NOMBRE_PRODUCTO
			,CH.ID_FONDEO
			,B.COD_CONCEPTO AS RUBRO
			,B.MON_PAGO MONTO
			,B.MON_PAGO_IVA
			,CASE WHEN A.IND_FORMA_PAGO = '' THEN 0 ELSE A.IND_FORMA_PAGO END IND_FORMA_PAGO
			,C.NUM_DESC_TIPO_CREDITO
			,CP.NOMBRE_CORTO
			,C.IND_ESTADO
			,CASE WHEN C.Ind_estado_Cont = 'VI' THEN 'NO' WHEN C.Ind_estado_Cont = 'VE' THEN 'SI' END CARTERA_VENCIDA
			,A.FEC_MOVIMIENTO
			,A.TIP_TRANSACCION
			,A.SUBTIP_TRANSAC
			,CH.IND_ETAPA
			,C.MON_CREDITO
			,[dbo].[FN_ORIGEN_FONDOS](C.COD_ORIGEN,C.COD_EMPRESA) AS CEDIDO 
			,C.FEC_APERTURA
			,A.Id_secuencia
            ,B.ID_REFERENCIA
			,case when exists(select * from Quiero_Confianza_Shadow.PR.PR_DEPOSITOS_X_IDENTIFICAR where id_carga = A.id_carga and id_deposito = A.id_deposito) then 2080 else CAST(A.Id_cuenta AS bigint) end
			,dbo.FN_ES_COVID(Q.Ind_Posposicion,Q.Fecha_Posposicion,Q.Num_Credito)
			,''
			,IIF(PF.PRIMER_APELLIDO IS NULL OR PF.PRIMER_APELLIDO = '', 'NOMBRE', PF.PRIMER_APELLIDO)
			,'REEST SN CAP COM'
			,@ID_POLIZA
            ,'' AS TIPO_VIVIENDA
			,case when exists(select * from Quiero_Confianza_shadow.PR.PR_ENCABEZADO_PAGO where num_asiento = A.num_asiento and Mon_movimiento = -A.Mon_movimiento) then 'SI' else 'NO' end
			,dbo.FN_TIPO_CANAL(C.TIP_TASA)
		FROM Quiero_Confianza_shadow.PR.PR_ENCABEZADO_PAGO A WITH (NOLOCK)
				INNER JOIN Quiero_Confianza_shadow.PR.PR_DETALLE_PAGO B WITH (NOLOCK) ON A.ID_SECUENCIA = B.ID_SECUENCIA
				INNER JOIN Quiero_Confianza_shadow.PR.PR_CREDITOS C WITH (NOLOCK) ON A.COD_EMPRESA = C.COD_EMPRESA AND A.NUM_CREDITO = C.NUM_CREDITO
				INNER JOIN Quiero_Confianza_shadow.PR.PR_TIPO_CREDITO P WITH (NOLOCK) ON C.TIP_CREDITO = P.TIP_CREDITO AND C.COD_EMPRESA = P.COD_EMPRESA
				LEFT JOIN Quiero_Confianza_shadow.CL.CL_PERSONAS_JURIDICAS PJ WITH (NOLOCK) ON C.COD_EMPRESA = PJ.COD_EMPRESA AND C.COD_CLIENTE = PJ.COD_CLIENTE
				LEFT JOIN Quiero_Confianza_shadow.CL.CL_PERSONAS_FISICAS PF WITH (NOLOCK) ON C.COD_EMPRESA = PF.COD_EMPRESA AND C.COD_CLIENTE = PF.COD_CLIENTE
				LEFT JOIN Quiero_Confianza_shadow.PR.PR_RUBRO_COBRO_X_CREDITO Q WITH (NOLOCK) ON Q.Num_Secuencia = B.Id_referencia
				    AND Q.Num_Credito = A.Num_credito AND Q.Num_Det_Secuencia = B.Num_det_secuencia AND Q.Cod_Rubro = B.Cod_concepto AND Q.Ind_Estado != 'N'
                LEFT JOIN PO.CONTROL_HISTORICO_TRASPASOS CH ON A.NUM_CREDITO = CH.NUM_CREDITO AND CH.FECHA_SISTEMA = @FECHA_ANT
				LEFT JOIN PO.PR_CREDITO_EXTRA CE ON CE.ID_EXTERNO = C.ID_EXTERNO
				LEFT JOIN PO.PR_CREDITO_PRODUCTO CP ON CP.ID_PRODUCTO = CE.ID_PRODUCTO
		WHERE C.IND_ESTADO IN ('C', 'D')
				AND C.IND_LINEA = 'N'
				AND A.NUM_CREDITO IN (SELECT * FROM #CREDITOS_REESTRUCTURA)
				AND A.TIP_TRANSACCION !=3  --Evita que se traigan desembolsos que se jalan en SP FIRMA
				AND NOT (TIP_TRANSACCION = 4 AND SUBTIP_TRANSAC = 5)
				AND A.ID_CUENTA IN ('140103009001','140103009002','140103009003')
                and A.mon_movimiento > 0 -- no se consideran cancelaciones
				AND A.FEC_MOVIMIENTO = @FECHA_INICIO
				AND (B.MON_PAGO <> 0 OR B.MON_PAGO_IVA <> 0)
				AND NOT (B.Cod_concepto LIKE '%SEGURO%' OR B.Cod_concepto = 'CARGO_PORCENTAJE')-- DESCARATR TODOS LOS SEGUROS
				

		-- ====== REESTRUCTURA INDICADA POR CAMBIO DE NUC ============

		--DIA ACTUAL
		SELECT * INTO #CRED FROM PO.CONTROL_HISTORICO_TRASPASOS WHERE FECHA_SISTEMA = DATEADD(D,1,@FECHA_INICIO) AND NUM_DESC_TIPO_CREDITO IN (12,13,14,15,28,   2,18,27)
		--DIA ANTERIOR
		SELECT * INTO #CRED_ANT FROM PO.CONTROL_HISTORICO_TRASPASOS WHERE FECHA_SISTEMA = @FECHA_INICIO AND NUM_DESC_TIPO_CREDITO IN (12,13,14,15,28,   2,18,27)
		
		SELECT A.NUM_CREDITO
		INTO #CREDITOS_TRASPASO
		FROM #CRED I
			INNER JOIN #CRED_ANT A ON I.NUM_CREDITO = A.NUM_CREDITO
		WHERE I.ID_EXTERNO <> A.ID_EXTERNO

		-- SALDOS COVID
		SELECT NUM_CREDITO,'S' as COVID,'S' AS BALANCE, RUBRO, SALDO, SALDO_IVA
		INTO #SALDOS_COVID
		FROM [CIERRE].[SAF_SALDOS] A
		WHERE FECHA_SISTEMA=@FECHA_INICIO AND TIPO='C' AND RUBRO NOT IN ('PRINCIPAL_VENCIDO','SEGURO_DANOS','SEGURO_VIDA','CARGO_PORCENTAJE','INTERES_NO_EXIGIBLES')
			AND NUM_CREDITO IN (SELECT NUM_CREDITO FROM #CREDITOS_TRASPASO)

		-- SALDOS ORDEN
		SELECT NUM_CREDITO,'' as COVID,'N' AS BALANCE, RUBRO, SALDO, SALDO_IVA
		INTO #SALDOS_ORDEN
		FROM [CIERRE].[SAF_SALDOS] A
		WHERE FECHA_SISTEMA=@FECHA_INICIO AND TIPO='O' AND RUBRO NOT IN ('PRINCIPAL_VENCIDO','SEGURO_DANOS','SEGURO_VIDA','CARGO_PORCENTAJE','INTERES_NO_EXIGIBLES')
			AND NUM_CREDITO IN (SELECT NUM_CREDITO FROM #CREDITOS_TRASPASO)

		-- SALDOS INTERES NO EXIGIBLES
		SELECT NUM_CREDITO,'' as COVID,'' AS BALANCE, 'INTERESES' AS RUBRO, SALDO, SALDO_IVA
		INTO #SALDOS_INTERES_NO_EXIGIBLE
		FROM [CIERRE].[SAF_SALDOS] A
		WHERE FECHA_SISTEMA=@FECHA_INICIO AND TIPO='N' AND RUBRO IN ('INTERES_NO_EXIGIBLES')
			AND NUM_CREDITO IN (SELECT NUM_CREDITO FROM #CREDITOS_TRASPASO)

		-- SALDOS NORMAL SIN COVID SIN ORDEN
		SELECT N.NUM_CREDITO,'N' as COVID,'S' AS BALANCE, N.RUBRO
			, ISNULL(N.SALDO,0) + ISNULL(I.SALDO,0) - ISNULL(C.SALDO,0) - ISNULL(O.SALDO,0) AS SALDO
			, ISNULL(N.SALDO_IVA,0) + ISNULL(I.SALDO_IVA,0) - ISNULL(C.SALDO_IVA,0) - ISNULL(O.SALDO_IVA,0) AS SALDO_IVA
		INTO #SALDOS
		FROM [CIERRE].[SAF_SALDOS] N LEFT JOIN
			#SALDOS_COVID C ON N.NUM_CREDITO = C.NUM_CREDITO AND N.RUBRO = C.RUBRO LEFT JOIN
			#SALDOS_ORDEN O ON N.NUM_CREDITO = O.NUM_CREDITO AND N.RUBRO = O.RUBRO LEFT JOIN
			#SALDOS_INTERES_NO_EXIGIBLE I ON N.NUM_CREDITO = I.NUM_CREDITO AND N.RUBRO = I.RUBRO
		WHERE FECHA_SISTEMA=@FECHA_INICIO AND TIPO='N' AND N.RUBRO NOT IN ('PRINCIPAL_VENCIDO','SEGURO_DANOS','SEGURO_VIDA','CARGO_PORCENTAJE','INTERES_NO_EXIGIBLES')
			AND N.NUM_CREDITO IN (SELECT NUM_CREDITO FROM #CREDITOS_TRASPASO)
		

		INSERT INTO #SALDOS
		select * from #SALDOS_ORDEN

		INSERT INTO #SALDOS
		select * from #SALDOS_COVID

		DELETE FROM #SALDOS WHERE SALDO = 0 AND SALDO_IVA = 0


		INSERT INTO PO.SAF_MOV_ABONO(
			ID_EXTERNO, NUM_CREDITO, NOM_CLIENTE, CUENTA_CARGO, CUENTA_ABONO, ID_PRODUCTO, NOMBRE_PRODUCTO, ID_FONDEO, RUBRO, MONTO
			,MON_PAGO_IVA, IND_FORMA_PAGO, ID_TIPO_CREDITO, TIPO_CREDITO, IND_ESTADO, CARTERA_VENCIDA, FECHA_MOVIMIENTO
			,TIP_TRANSACCION, SUBTIP_TRANSAC, IND_ETAPA, MON_CREDITO, CEDIDO, FEC_APERTURA, ID_SECUENCIA, ID_REFERENCIA, ID_CUENTA, IND_COVID, 
			CONCEPTO_FINAL, APELLIDO, TABLA_ORIGEN, ID_POLIZA, TIPO_VIVIENDA, REVERSO, CANAL)
		SELECT C.ID_EXTERNO
			,C.NUM_CREDITO
			,dbo.FN_FORMA_NOMBRE(PF.PRIMER_APELLIDO, PF.SEGUNDO_APELLIDO, PF.PRIMER_NOMBRE, PF.SEGUNDO_NOMBRE, PJ.RAZON_SOCIAL, PJ.NOM_COMERCIAL)
			,'' AS CUENTA_CARGO
			,'' AS CUENTA_ABONO
			,ISNULL((SELECT TOP 1 NUM_PRODUCTO FROM PO.PR_CAT_PRODUCTO WHERE ID_SAF = P.TIP_CREDITO), P.TIP_CREDITO) ID_PRODUCTO
			,CP.NOMBRE_CORTO NOMBRE_PRODUCTO
			,CH.ID_FONDEO
			,A.RUBRO AS RUBRO
			,A.SALDO AS MONTO
			,A.SALDO_IVA AS MON_PAGO_IVA
			,0 AS IND_FORMA_PAGO
			,C.NUM_DESC_TIPO_CREDITO
			,CP.NOMBRE_CORTO
			,C.IND_ESTADO
			,CASE WHEN C.Ind_estado_Cont = 'VI' THEN 'NO' WHEN C.Ind_estado_Cont = 'VE' THEN 'SI' END CARTERA_VENCIDA
			,@FECHA_INICIO AS FECHA_SISTEMA
			,0 AS TIP_TRANSACCION
			,0 AS SUBTIP_TRANSAC
			,CH.IND_ETAPA
			,C.MON_CREDITO
			,[dbo].[FN_ORIGEN_FONDOS](C.COD_ORIGEN,C.COD_EMPRESA) AS CEDIDO 
			,C.FEC_APERTURA
			,0 AS Id_secuencia
            ,0 AS ID_REFERENCIA
			,0 AS ID_CUENTA
			,A.COVID AS IND_COVID
			,''
			,IIF(PF.PRIMER_APELLIDO IS NULL OR PF.PRIMER_APELLIDO = '', 'NOMBRE', PF.PRIMER_APELLIDO)
			,'REEST SN CAP COM '+CASE WHEN BALANCE='S' THEN 'B' ELSE 'O' END AS TABLA_ORIGEN
			,@ID_POLIZA
            ,'' AS TIPO_VIVIENDA
			,'NO' AS REVERSO
			,dbo.FN_TIPO_CANAL(C.TIP_TASA)
		FROM #SALDOS A
				INNER JOIN Quiero_Confianza_shadow.PR.PR_CREDITOS C WITH (NOLOCK) ON '001' = C.COD_EMPRESA AND A.NUM_CREDITO = C.NUM_CREDITO
				INNER JOIN Quiero_Confianza_shadow.PR.PR_TIPO_CREDITO P WITH (NOLOCK) ON C.TIP_CREDITO = P.TIP_CREDITO AND C.COD_EMPRESA = P.COD_EMPRESA
				LEFT JOIN Quiero_Confianza_shadow.CL.CL_PERSONAS_JURIDICAS PJ WITH (NOLOCK) ON C.COD_EMPRESA = PJ.COD_EMPRESA AND C.COD_CLIENTE = PJ.COD_CLIENTE
				LEFT JOIN Quiero_Confianza_shadow.CL.CL_PERSONAS_FISICAS PF WITH (NOLOCK) ON C.COD_EMPRESA = PF.COD_EMPRESA AND C.COD_CLIENTE = PF.COD_CLIENTE
                LEFT JOIN PO.CONTROL_HISTORICO_TRASPASOS CH ON A.NUM_CREDITO = CH.NUM_CREDITO AND CH.FECHA_SISTEMA = @FECHA_INICIO
				LEFT JOIN PO.PR_CREDITO_EXTRA CE ON CE.ID_EXTERNO = C.ID_EXTERNO
				LEFT JOIN PO.PR_CREDITO_PRODUCTO CP ON CP.ID_PRODUCTO = CE.ID_PRODUCTO


		-- ====== ACTUALIZACION DE CUENTA BANCO ============

        UPDATE H
		SET H.BANCO_RECEPTOR = C.DES_CUENTA+'/'+C.NUM_CUENTA
		FROM PO.SAF_MOV_ABONO H
			INNER JOIN Quiero_Confianza_shadow.BA.BA_CTA_CORRIENTE C ON H.ID_CUENTA = CAST( C.ID_CUENTA AS VARCHAR(50))
		WHERE H.FECHA_MOVIMIENTO = @FECHA_INICIO
			AND H.ID_POLIZA = @ID_POLIZA

		
		-- ======  CALIFICACION BASE DEL CONCEPTO DEACUERDO A REGLAS GLOBALES ============
		UPDATE PO.SAF_MOV_ABONO
		SET CONCEPTO = CONCAT(CASE
					WHEN TIP_TRANSACCION IN (0,4) THEN 'CMR PAGO '
					ELSE ''
				END,
                IIF(IND_COVID = 'S', 'COVID ', ''), --# Si el registro tiene COVID le agrega la palabra
				IIF(TIP_TRANSACCION = 113 OR (TIP_TRANSACCION = 4 AND RUBRO = 'SALDO_FAVOR'), '', IIF(CONCEPTO='PREPAGO',dbo.FN_RUBRO_POL(RUBRO)+' CANC ',dbo.FN_RUBRO_POL(RUBRO))),  --# Si no es saldo a favor le agrega el rubro
				-- tipo_credito
				CASE WHEN TIP_TRANSACCION = 113 OR (TIP_TRANSACCION = 4 AND RUBRO = 'SALDO_FAVOR') THEN ''
					ELSE ' '+TIPO_CREDITO+' '
				END,
				-- canal
				CASE WHEN TIP_TRANSACCION = 113 OR (TIP_TRANSACCION = 4 AND RUBRO = 'SALDO_FAVOR') THEN ''
					ELSE CANAL
				END,
				-- espacio para continuar con cedido
				IIF(TIP_TRANSACCION = 113 OR (TIP_TRANSACCION = 4 AND RUBRO = 'SALDO_FAVOR'),'',' '),
				/*IIF(ID_PRODUCTO= 50,'', CONCAT(TIPO_VIVIENDA, ' ')),*/
				-- 'NO' OPCIONAL PARA CEDIDO
				CASE WHEN TIP_TRANSACCION = 113 OR (TIP_TRANSACCION = 4 AND RUBRO = 'SALDO_FAVOR') THEN ''
					ELSE IIF(ID_FONDEO = 2, 'NO ', '')
				END,
				-- RESTRINGIDO
				CASE WHEN TIP_TRANSACCION = 113 OR (TIP_TRANSACCION = 4 AND RUBRO = 'SALDO_FAVOR') THEN ''
					ELSE 'RESTRINGIDO '
				END,
				-- ETAPA
                CASE WHEN TIP_TRANSACCION = 113 OR (TIP_TRANSACCION = 4 AND RUBRO = 'SALDO_FAVOR') THEN ''
					ELSE CAST(IND_ETAPA AS VARCHAR(1))
				END) 
		WHERE FECHA_MOVIMIENTO = @FECHA_INICIO
			AND ID_POLIZA = @ID_POLIZA AND RUBRO != '' AND ID_TIPO_CREDITO != 5

		-- GENERACION DE CONCEPTOS MEZZANINE COMERCIALES
		UPDATE PO.SAF_MOV_ABONO
		SET CONCEPTO = CONCAT(CASE
					WHEN TIP_TRANSACCION IN (0,4) THEN 'CMR DCM PAGO '
					ELSE ''
				END,
                IIF(TIP_TRANSACCION = 113 OR (TIP_TRANSACCION = 4 AND RUBRO = 'SALDO_FAVOR'), '', IIF(CONCEPTO='PREPAGO',dbo.FN_RUBRO_POL(RUBRO)+' CANC ',dbo.FN_RUBRO_POL(RUBRO)))  --# Si no es saldo a favor le agrega el rubro
				) 
		WHERE FECHA_MOVIMIENTO = @FECHA_INICIO
			AND ID_POLIZA = @ID_POLIZA AND RUBRO != '' AND ID_TIPO_CREDITO = 5

		UPDATE PO.SAF_MOV_ABONO   
		SET CONCEPTO_ANT = 
			CONCAT(CASE
					WHEN TIP_TRANSACCION IN (0,4) THEN 'CMR PAGO '
					ELSE ''
				END,
                --IIF(IND_COVID = 'S', 'COVID ', ''), --# Si el registro tiene COVID le agrega la palabra
				dbo.FN_RUBRO_POL(RUBRO), ' ',  --# Si no es saldo a favor le agrega el rubro
				TIPO_CREDITO+' ',
				CANAL,
				-- espacio para continuar con cedido
				IIF(TIP_TRANSACCION = 113 OR (TIP_TRANSACCION = 4 AND RUBRO = 'SALDO_FAVOR'),'',' '),
				/*IIF(ID_PRODUCTO= 50,'', CONCAT(TIPO_VIVIENDA, ' ')),*/
				-- 'NO' OPCIONAL PARA CEDIDO
				CASE WHEN TIP_TRANSACCION = 113 OR (TIP_TRANSACCION = 4 AND RUBRO = 'SALDO_FAVOR') THEN ''
					ELSE IIF(ID_FONDEO = 2, 'NO ', '')
				END,
				-- RESTRINGIDO
				CASE WHEN TIP_TRANSACCION = 113 OR (TIP_TRANSACCION = 4 AND RUBRO = 'SALDO_FAVOR') THEN ''
					ELSE 'RESTRINGIDO '
				END,
				-- ETAPA
                CASE WHEN TIP_TRANSACCION = 113 OR (TIP_TRANSACCION = 4 AND RUBRO = 'SALDO_FAVOR') THEN ''
					ELSE CAST(IND_ETAPA AS VARCHAR(1))
				END)
        WHERE FECHA_MOVIMIENTO = @FECHA_INICIO
			AND ID_POLIZA = @ID_POLIZA AND ID_TIPO_CREDITO != 5

		-- GENERACION DE CONCEPTOS MEZZANINE COMERCIALES
		UPDATE PO.SAF_MOV_ABONO   
		SET CONCEPTO_ANT = 
			CONCAT(CASE
					WHEN TIP_TRANSACCION IN (0,4) THEN 'CMR DCM PAGO '
					ELSE ''
				END,
                --IIF(IND_COVID = 'S', 'COVID ', ''), --# Si el registro tiene COVID le agrega la palabra
				dbo.FN_RUBRO_POL(RUBRO)  --# Si no es saldo a favor le agrega el rubro
				)
        WHERE FECHA_MOVIMIENTO = @FECHA_INICIO
			AND ID_POLIZA = @ID_POLIZA  AND ID_TIPO_CREDITO = 5


		UPDATE PO.SAF_MOV_ABONO
		SET CONCEPTO = REPLACE(CONCEPTO, 'PAGO ', 'PAGO CCO '),
			CONCEPTO_ANT= REPLACE(CONCEPTO_ANT, 'PAGO ', 'PAGO CCO ')
        WHERE FECHA_MOVIMIENTO = @FECHA_INICIO
			AND ID_POLIZA = @ID_POLIZA
			AND TABLA_ORIGEN IN ('REEST SN CAP COM O')
			AND RUBRO NOT IN ('PRINCIPAL')
			AND ((ID_TIPO_CREDITO != 5) OR
			(ID_TIPO_CREDITO = 5 AND RUBRO NOT LIKE '%SEGURO%' AND RUBRO NOT LIKE '%IVA%')) -- MEZZANINE
		
		------------- ###################################### ------------------------------------------------
		------------- ###################################### ------------------------------------------------
		
		--# Variables a usar para lectura linea a linea
		DECLARE  @ID_EXTERNO		VARCHAR(15),	@NUM_CREDITO		NUMERIC(8, 0), 
				 @ID_FONDEO		    INT, 			@ID_PRODUCTO		NUMERIC(3, 0), 
				 @TIP_TRANSACCION   VARCHAR(5),		@SUBTIP_TRANSAC		VARCHAR(5), 
				 @RUBRO			    VARCHAR(30),	@MONTO				NUMERIC(16, 2), 
				 @MON_PAGO_IVA		NUMERIC(16, 2), @TIPO_CREDITO		VARCHAR(255), 
