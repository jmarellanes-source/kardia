CREATE PROCEDURE [PO].[SP_COM_CASTIGOS]
(
	@FECHA_INICIO DATE
)
AS
BEGIN
    SET NOCOUNT ON

    declare @ID_POLIZA int = 50

	BEGIN TRY
		BEGIN TRANSACTION
			
		-- SE BORRA INFORMACION DEL DIA EN CASO DE QUE EXISTE
		DELETE FROM PO.SAF_MOV_TRASPASO WHERE FECHA_MOVIMIENTO = @FECHA_INICIO AND ID_POLIZA = @ID_POLIZA
		--------------------------------- EXTRACCION --------------------------------------------
		--DIA ACTUAL
		SELECT * INTO #CRED FROM PO.CONTROL_HISTORICO_TRASPASOS WHERE FECHA_SISTEMA = @FECHA_INICIO AND NUM_DESC_TIPO_CREDITO IN (25,    29)
		--DIA ANTERIOR
		SELECT * INTO #CRED_ANT FROM PO.CONTROL_HISTORICO_TRASPASOS WHERE FECHA_SISTEMA = DATEADD(D,-1,@FECHA_INICIO) AND NUM_DESC_TIPO_CREDITO IN (5,   12,13,14,15,28,     2,18,27)
		--------------------------------- FIN EXTRACCION --------------------------------------------
		
		--------------------------------- LOGICA DE TRASPASOS --------------------------------------------		
		-- DECLARACION DE VARIABLES
		DECLARE  @ID_EXTERNO			VARCHAR(15),	@NUM_CREDITO		INT
				 ,@NOM_CLIENTE		    VARCHAR(250)
				 ,@ID_PRODUCTO		    INT
				 ,@ID_TIPO_CREDITO		INT
				 ,@IND_ETAPA_ACTUAL	    INT,            @IND_ETAPA_ANTERIOR	INT = 0
				 ,@ID_FONDEO_ACTUAL		INT,			@ID_FONDEO_ANTERIOR	INT
                 ,@TIPO_VIVIENDA		VARCHAR(50),    @TIPO_V_ANT			VARCHAR(150)
				 ,@ES_TRASPASO		    VARCHAR(1) = 'S'
				 ,@LEYENDA				VARCHAR(70),	@EL_ID_FONDEO		VARCHAR(16)
				 ,@EL_ID_PRODUCTO		VARCHAR(11)
				 ,@TIPO_TRASPASO		INT = 0
				 ,@CRED_ANT		    	INT
                 ,@IND_ETAPA_RIESGO_MANUAL VARCHAR(1),	@MAX_INDICE		INT
				 ,@INDICE				INT = 0,		@RUBRO			    VARCHAR(30)
				 ,@FECHA_MOVIMIENTO	DATE,				@IND_ESTADO		VARCHAR(2)
				 ,@FECHA_ACTUAL	DATE,					@ID_UNICO			VARCHAR(150)
				 ,@CONCEPTO_FINAL	VARCHAR(30),		@NUM_CREDITO_ANT	NUMERIC(8, 0) = 0
				 ,@TOTAL				DECIMAL(16,2) = 0,	@EL_RUBRO			VARCHAR(30) = ''
				 ,@ORDEN				DECIMAL(16,2),	@BANDERA			INT
				 ,@TIPO_CREDITO			VARCHAR(50),	@CANAL				VARCHAR(30)

		DECLARE @MONTO NUMERIC(16,2) = 0,
			@MON_TRASPASO_COVID NUMERIC(16,2) = 0,
            @FECHA_INICIO_REF date,
            @FECHA_SISTEMA date

		declare @MONTO_OFFSET numeric(16,6),@ORDEN_TOT numeric(16,6),@DIAS_PERIODO_INTERNO int,@fecha_ref date, @Dias_offset int
		--# variables para uso de la separacion balance/orden
		DECLARE @SUMA89 NUMERIC(16, 2), @SUMA90 NUMERIC(16, 2), @FAVOR NUMERIC(16, 2), @IMPAGO DATE, @ETAPA_3_INI  DATE, @DIA_CORTE int,@DIA_CORTE_REAL INT
		

        DECLARE db_cursor_poliza_traspaso CURSOR FOR
		
		    SELECT C.ID_EXTERNO, A.NUM_CREDITO, CL.NOM_CLIENTE, C.NUM_DESC_TIPO_CREDITO,
			    ISNULL((SELECT TOP 1 NUM_PRODUCTO FROM PO.PR_CAT_PRODUCTO WHERE ID_SAF = P.TIP_CREDITO), P.TIP_CREDITO) ID_PRODUCTO
                , I.IND_ETAPA, A.IND_ETAPA
                --, I.TIPO_VIVIENDA, A.TIPO_VIVIENDA
                , I.ID_FONDEO, A.ID_FONDEO
                , 'N'
				, CP.NOMBRE_CORTO TIPO_CREDITO
				, dbo.FN_TIPO_CANAL(C.TIP_TASA)
		    FROM #CRED I
		    INNER JOIN #CRED_ANT A ON I.NUM_CREDITO = A.NUM_CREDITO
		    LEFT JOIN Quiero_Confianza_shadow.PR.PR_CREDITOS C ON I.NUM_CREDITO = C.NUM_CREDITO
		    LEFT JOIN Quiero_Confianza_shadow.CL.CL_CLIENTES CL ON C.COD_CLIENTE = CL.COD_CLIENTE
		    LEFT JOIN Quiero_Confianza_shadow.PR.PR_TIPO_CREDITO P ON C.TIP_CREDITO = P.TIP_CREDITO AND C.COD_EMPRESA = P.COD_EMPRESA
			LEFT JOIN PO.PR_CREDITO_EXTRA CE ON CE.ID_EXTERNO = C.ID_EXTERNO
			LEFT JOIN PO.PR_CREDITO_PRODUCTO CP ON CP.ID_PRODUCTO = CE.ID_PRODUCTO
		   
        OPEN db_cursor_poliza_traspaso
            FETCH NEXT FROM db_cursor_poliza_traspaso
            INTO  @ID_EXTERNO, @NUM_CREDITO, @NOM_CLIENTE, @ID_TIPO_CREDITO, @ID_PRODUCTO
                , @IND_ETAPA_ACTUAL, @IND_ETAPA_ANTERIOR, /*@TIPO_VIVIENDA, @TIPO_V_ANT,*/ @ID_FONDEO_ACTUAL ,@ID_FONDEO_ANTERIOR
                , @IND_ETAPA_RIESGO_MANUAL, @TIPO_CREDITO, @CANAL

         WHILE @@FETCH_STATUS = 0
        BEGIN

    set @FECHA_INICIO_REF =  @FECHA_INICIO 
    set @FECHA_SISTEMA = DATEADD(DD,1,@FECHA_INICIO)

	-- SE INSERTA REGISTRO EN TABLA DE CASTIGOS
    exec [PO].[SP_SAF_CASTIGO_AGR] @NUM_CREDITO,@FECHA_INICIO
	
	-- # TRASPASO DE INTERESES
	SELECT
		@MONTO =
		ISNULL((SELECT SUM(SAL_RUBRO) FROM Quiero_Confianza_Shadow.PR.PR_RUBRO_COBRO_X_CREDITO A 
			WHERE FEC_COBRO <= @FECHA_INICIO AND A.IND_ESTADO = 'P' AND A.NUM_CREDITO = @NUM_CREDITO AND A.Cod_Rubro = 'INTERESES'
			AND dbo.FN_ES_COVID(A.Ind_Posposicion,A.Fecha_Posposicion,A.NUM_CREDITO) != 'S'),0) +
		ISNULL((SELECT mon_int_acumulado FROM Quiero_Confianza_Shadow.PR.PR_RUBRO_COBRO_X_CREDITO A 
			WHERE @FECHA_INICIO > FEC_BASE_CALC AND @FECHA_SISTEMA <= FEC_COBRO AND A.IND_ESTADO = 'P' AND 
			A.NUM_CREDITO = @NUM_CREDITO AND A.Cod_Rubro = 'INTERESES' AND dbo.FN_ES_COVID(A.Ind_Posposicion,A.Fecha_Posposicion,A.NUM_CREDITO) != 'S'),0) -
		ISNULL((SELECT SUM(MON_DIARIO) FROM Quiero_Confianza_shadow.PR.PR_CALCULO_INTERESES_DIA
		WHERE NUM_CREDITO = @NUM_CREDITO
		AND FECHA_CALCULO IN(@FECHA_INICIO_REF, @FECHA_SISTEMA)),0), -- SE EJECUTA CUANDO EL SISTEMA ESTA EN T+1
					
	-- # TRASPASO DE INTERESES COVID
		@MON_TRASPASO_COVID = 
		ISNULL((SELECT SUM(SAL_RUBRO) FROM Quiero_Confianza_Shadow.PR.PR_RUBRO_COBRO_X_CREDITO A 
			WHERE FEC_COBRO <=@FECHA_INICIO AND A.IND_ESTADO = 'P' AND A.NUM_CREDITO = @NUM_CREDITO AND A.Cod_Rubro = 'INTERESES'
			AND dbo.FN_ES_COVID(A.Ind_Posposicion,A.Fecha_Posposicion,A.NUM_CREDITO) = 'S'),0) +
		ISNULL((SELECT mon_int_acumulado FROM Quiero_Confianza_Shadow.PR.PR_RUBRO_COBRO_X_CREDITO A 
			WHERE @FECHA_INICIO > FEC_BASE_CALC AND @FECHA_SISTEMA <= FEC_COBRO AND A.IND_ESTADO = 'P' AND 
			A.NUM_CREDITO = @NUM_CREDITO AND A.Cod_Rubro = 'INTERESES' AND dbo.FN_ES_COVID(A.Ind_Posposicion,A.Fecha_Posposicion,A.NUM_CREDITO) = 'S'),0)
				
	INSERT INTO PO.SAF_MOV_TRASPASO (ID_EXTERNO, NUM_CREDITO, NOM_CLIENTE, ID_FONDEO, ID_PRODUCTO, CONCEPTO_FINAL, RUBRO,
	MONTO, ID_TIPO_CREDITO, TIPO_VIVIENDA, FECHA_MOVIMIENTO, IND_ETAPA, TABLA_ORIGEN, ID_POLIZA, CONCEPTO, COD_CLIENTE,
	IND_ESTADO, TIPO_CREDITO, CANAL)
	SELECT
		@ID_EXTERNO, @NUM_CREDITO, @NOM_CLIENTE, @ID_FONDEO_ACTUAL, @ID_PRODUCTO, 
		CONCAT(@LEYENDA, @ID_EXTERNO, ' ', @NOM_CLIENTE),
		'INTERESES', @MONTO, @ID_TIPO_CREDITO, '', @FECHA_INICIO, @IND_ETAPA_ACTUAL,
		'CASTIGO COM', @ID_POLIZA, '','','P', @TIPO_CREDITO, @CANAL
	
	INSERT INTO PO.SAF_MOV_TRASPASO (ID_EXTERNO, NUM_CREDITO, NOM_CLIENTE, ID_FONDEO, ID_PRODUCTO, CONCEPTO_FINAL, RUBRO,
	MONTO, ID_TIPO_CREDITO, TIPO_VIVIENDA, FECHA_MOVIMIENTO, IND_ETAPA, TABLA_ORIGEN, ID_POLIZA, CONCEPTO, COD_CLIENTE,
	IND_ESTADO, IND_COVID, TIPO_CREDITO, CANAL)
	SELECT 
		@ID_EXTERNO, @NUM_CREDITO, @NOM_CLIENTE, @ID_FONDEO_ACTUAL, @ID_PRODUCTO, 
		CONCAT(@LEYENDA, @ID_EXTERNO, ' ', @NOM_CLIENTE),
		'INTERESES', @MON_TRASPASO_COVID, @ID_TIPO_CREDITO, '', @FECHA_INICIO, @IND_ETAPA_ACTUAL,
		'CASTIGO COM', @ID_POLIZA, '','','P','S', @TIPO_CREDITO, @CANAL
	
	-- # TRASPASO DE IVA INTERESES
	SELECT
		@MONTO =
		CASE WHEN (SELECT IND_IVA FROM Quiero_Confianza_Shadow.PR.PR_RUBRO_X_CREDITO WHERE NUM_CREDITO = @NUM_CREDITO AND COD_RUBRO = 'INTERESES') = 'N' THEN 0
		ELSE 
		ISNULL((SELECT SUM(SAL_IVA) FROM Quiero_Confianza_Shadow.PR.PR_RUBRO_COBRO_X_CREDITO A 
			WHERE FEC_COBRO <= @FECHA_INICIO AND A.IND_ESTADO = 'P' AND A.NUM_CREDITO = @NUM_CREDITO AND A.Cod_Rubro = 'INTERESES'
			AND dbo.FN_ES_COVID(A.Ind_Posposicion,A.Fecha_Posposicion,A.NUM_CREDITO) != 'S'),0) 
			+ 0.16*
		(ISNULL((SELECT mon_int_acumulado FROM Quiero_Confianza_Shadow.PR.PR_RUBRO_COBRO_X_CREDITO A 
			WHERE @FECHA_INICIO > FEC_BASE_CALC AND @FECHA_SISTEMA <= FEC_COBRO AND A.IND_ESTADO = 'P' AND 
			A.NUM_CREDITO = @NUM_CREDITO AND A.Cod_Rubro = 'INTERESES' AND dbo.FN_ES_COVID(A.Ind_Posposicion,A.Fecha_Posposicion,A.NUM_CREDITO) != 'S'),0))
			-
			0.16*
		(ISNULL((SELECT SUM(MON_DIARIO) FROM Quiero_Confianza_shadow.PR.PR_CALCULO_INTERESES_DIA A
		WHERE A.NUM_CREDITO = @NUM_CREDITO
		AND FECHA_CALCULO IN(@FECHA_INICIO_REF, @FECHA_SISTEMA )),0)) -- SE EJECUTA CUANDO EL SISTEMA ESTA EN T+1
		END,			
	-- # TRASPASO DE IVA INTERESES COVID
		@MON_TRASPASO_COVID = 
		CASE WHEN (SELECT IND_IVA FROM Quiero_Confianza_Shadow.PR.PR_RUBRO_X_CREDITO WHERE NUM_CREDITO = @NUM_CREDITO AND COD_RUBRO = 'INTERESES') = 'N' THEN 0
		ELSE
		ISNULL((SELECT SUM(SAL_IVA) FROM Quiero_Confianza_Shadow.PR.PR_RUBRO_COBRO_X_CREDITO A 
			WHERE FEC_COBRO <=@FECHA_INICIO AND A.IND_ESTADO = 'P' AND A.NUM_CREDITO = @NUM_CREDITO AND A.Cod_Rubro = 'INTERESES'
			AND dbo.FN_ES_COVID(A.Ind_Posposicion,A.Fecha_Posposicion,A.NUM_CREDITO) = 'S'),0) 
			+
		0.16*
		(ISNULL((SELECT mon_int_acumulado FROM Quiero_Confianza_Shadow.PR.PR_RUBRO_COBRO_X_CREDITO A 
			WHERE @FECHA_INICIO > FEC_BASE_CALC AND @FECHA_SISTEMA <= FEC_COBRO AND A.IND_ESTADO = 'P' AND 
			A.NUM_CREDITO = @NUM_CREDITO AND A.Cod_Rubro = 'INTERESES' AND dbo.FN_ES_COVID(A.Ind_Posposicion,A.Fecha_Posposicion,A.NUM_CREDITO) = 'S'),0))
		END
		
	INSERT INTO PO.SAF_MOV_TRASPASO (ID_EXTERNO, NUM_CREDITO, NOM_CLIENTE, ID_FONDEO, ID_PRODUCTO, CONCEPTO_FINAL, RUBRO,
	MONTO, ID_TIPO_CREDITO, TIPO_VIVIENDA, FECHA_MOVIMIENTO, IND_ETAPA, TABLA_ORIGEN, ID_POLIZA, CONCEPTO, COD_CLIENTE,
	IND_ESTADO, TIPO_CREDITO, CANAL)
	SELECT
		@ID_EXTERNO, @NUM_CREDITO, @NOM_CLIENTE, @ID_FONDEO_ACTUAL, @ID_PRODUCTO, 
		CONCAT(@LEYENDA, @ID_EXTERNO, ' ', @NOM_CLIENTE),
		'IVA INTERESES', @MONTO, @ID_TIPO_CREDITO, '', @FECHA_INICIO, @IND_ETAPA_ACTUAL,
		'CASTIGO COM', @ID_POLIZA, '','','P', @TIPO_CREDITO, @CANAL
	
	INSERT INTO PO.SAF_MOV_TRASPASO (ID_EXTERNO, NUM_CREDITO, NOM_CLIENTE, ID_FONDEO, ID_PRODUCTO, CONCEPTO_FINAL, RUBRO,
	MONTO, ID_TIPO_CREDITO, TIPO_VIVIENDA, FECHA_MOVIMIENTO, IND_ETAPA, TABLA_ORIGEN, ID_POLIZA, CONCEPTO, COD_CLIENTE,
	IND_ESTADO, IND_COVID, TIPO_CREDITO, CANAL)
	SELECT 
		@ID_EXTERNO, @NUM_CREDITO, @NOM_CLIENTE, @ID_FONDEO_ACTUAL, @ID_PRODUCTO, 
		CONCAT(@LEYENDA, @ID_EXTERNO, ' ', @NOM_CLIENTE),
		'IVA INTERESES', @MON_TRASPASO_COVID, @ID_TIPO_CREDITO, '', @FECHA_INICIO, @IND_ETAPA_ACTUAL,
		'CASTIGO COM', @ID_POLIZA, '','','P','S', @TIPO_CREDITO, @CANAL

	-- # TRASPASO DE SEGURO_VIDA
	SELECT
		@MONTO =
		ISNULL((SELECT SUM(SAL_RUBRO) FROM Quiero_Confianza_Shadow.PR.PR_RUBRO_COBRO_X_CREDITO A WHERE 
		A.NUM_CREDITO = @NUM_CREDITO AND A.COD_RUBRO = 'SEGURO_VIDA' AND A.IND_ESTADO = 'P' AND dbo.FN_ES_COVID(A.Ind_Posposicion,A.Fecha_Posposicion,A.NUM_CREDITO) != 'S'
		AND Fec_Cobro <= @FECHA_INICIO),0),
	
	-- # TRASPASO SEGURO_VIDA COVID
		@MON_TRASPASO_COVID = 
		ISNULL((SELECT SUM(SAL_RUBRO) FROM Quiero_Confianza_Shadow.PR.PR_RUBRO_COBRO_X_CREDITO A WHERE 
		A.NUM_CREDITO = @NUM_CREDITO AND A.COD_RUBRO = 'SEGURO_VIDA' AND A.IND_ESTADO = 'P' AND dbo.FN_ES_COVID(A.Ind_Posposicion,A.Fecha_Posposicion,A.NUM_CREDITO) = 'S'
		AND Fec_Cobro <= @FECHA_INICIO),0)

	INSERT INTO PO.SAF_MOV_TRASPASO (ID_EXTERNO, NUM_CREDITO, NOM_CLIENTE, ID_FONDEO, ID_PRODUCTO, CONCEPTO_FINAL, RUBRO,
	MONTO, ID_TIPO_CREDITO, TIPO_VIVIENDA, FECHA_MOVIMIENTO, IND_ETAPA, TABLA_ORIGEN, ID_POLIZA, CONCEPTO, COD_CLIENTE,
	IND_ESTADO, TIPO_CREDITO, CANAL)
	SELECT
		@ID_EXTERNO, @NUM_CREDITO, @NOM_CLIENTE, @ID_FONDEO_ACTUAL, @ID_PRODUCTO, 
		CONCAT(@LEYENDA, @ID_EXTERNO, ' ', @NOM_CLIENTE),
		'SEGURO_VIDA', @MONTO, @ID_TIPO_CREDITO, '', @FECHA_INICIO, @IND_ETAPA_ACTUAL,
		'CASTIGO COM', @ID_POLIZA, '','','P', @TIPO_CREDITO, @CANAL

	INSERT INTO PO.SAF_MOV_TRASPASO (ID_EXTERNO, NUM_CREDITO, NOM_CLIENTE, ID_FONDEO, ID_PRODUCTO, CONCEPTO_FINAL, RUBRO,
	MONTO, ID_TIPO_CREDITO, TIPO_VIVIENDA, FECHA_MOVIMIENTO, IND_ETAPA, TABLA_ORIGEN, ID_POLIZA, CONCEPTO, COD_CLIENTE,
	IND_ESTADO, IND_COVID, TIPO_CREDITO, CANAL)
	SELECT 
		@ID_EXTERNO, @NUM_CREDITO, @NOM_CLIENTE, @ID_FONDEO_ACTUAL, @ID_PRODUCTO, 
		CONCAT(@LEYENDA, @ID_EXTERNO, ' ', @NOM_CLIENTE),
		'SEGURO_VIDA', @MON_TRASPASO_COVID, @ID_TIPO_CREDITO, '', @FECHA_INICIO, @IND_ETAPA_ACTUAL,
		'CASTIGO COM', @ID_POLIZA, '','','P','S', @TIPO_CREDITO, @CANAL

	-- # TRASPASO DE IVA SEGURO_VIDA
	SELECT
		@MONTO =
		ISNULL((SELECT SUM(SAL_IVA) FROM Quiero_Confianza_Shadow.PR.PR_RUBRO_COBRO_X_CREDITO A WHERE 
		A.NUM_CREDITO = @NUM_CREDITO AND A.COD_RUBRO = 'SEGURO_VIDA' AND A.IND_ESTADO = 'P' AND dbo.FN_ES_COVID(A.Ind_Posposicion,A.Fecha_Posposicion,A.NUM_CREDITO) != 'S'
		AND Fec_Cobro <= @FECHA_INICIO),0),
	
	-- # TRASPASO SEGURO_VIDA COVID
		@MON_TRASPASO_COVID = 
		ISNULL((SELECT SUM(SAL_IVA) FROM Quiero_Confianza_Shadow.PR.PR_RUBRO_COBRO_X_CREDITO A WHERE 
		A.NUM_CREDITO = @NUM_CREDITO AND A.COD_RUBRO = 'SEGURO_VIDA' AND A.IND_ESTADO = 'P' AND dbo.FN_ES_COVID(A.Ind_Posposicion,A.Fecha_Posposicion,A.NUM_CREDITO) = 'S'
		AND Fec_Cobro <= @FECHA_INICIO),0)

	INSERT INTO PO.SAF_MOV_TRASPASO (ID_EXTERNO, NUM_CREDITO, NOM_CLIENTE, ID_FONDEO, ID_PRODUCTO, CONCEPTO_FINAL, RUBRO,
	MONTO, ID_TIPO_CREDITO, TIPO_VIVIENDA, FECHA_MOVIMIENTO, IND_ETAPA, TABLA_ORIGEN, ID_POLIZA, CONCEPTO, COD_CLIENTE,
	IND_ESTADO, TIPO_CREDITO, CANAL)
	SELECT
		@ID_EXTERNO, @NUM_CREDITO, @NOM_CLIENTE, @ID_FONDEO_ACTUAL, @ID_PRODUCTO, 
		CONCAT(@LEYENDA, @ID_EXTERNO, ' ', @NOM_CLIENTE),
		'IVA SEGURO_VIDA', @MONTO, @ID_TIPO_CREDITO, '', @FECHA_INICIO, @IND_ETAPA_ACTUAL,
		'CASTIGO COM', @ID_POLIZA, '','','P', @TIPO_CREDITO, @CANAL

	INSERT INTO PO.SAF_MOV_TRASPASO (ID_EXTERNO, NUM_CREDITO, NOM_CLIENTE, ID_FONDEO, ID_PRODUCTO, CONCEPTO_FINAL, RUBRO,
	MONTO, ID_TIPO_CREDITO, TIPO_VIVIENDA, FECHA_MOVIMIENTO, IND_ETAPA, TABLA_ORIGEN, ID_POLIZA, CONCEPTO, COD_CLIENTE,
	IND_ESTADO, IND_COVID, TIPO_CREDITO, CANAL)
	SELECT 
		@ID_EXTERNO, @NUM_CREDITO, @NOM_CLIENTE, @ID_FONDEO_ACTUAL, @ID_PRODUCTO, 
		CONCAT(@LEYENDA, @ID_EXTERNO, ' ', @NOM_CLIENTE),
		'IVA SEGURO_VIDA', @MON_TRASPASO_COVID, @ID_TIPO_CREDITO, '', @FECHA_INICIO, @IND_ETAPA_ACTUAL,
		'CASTIGO COM', @ID_POLIZA, '','','P','S', @TIPO_CREDITO, @CANAL

	-- # TRASPASO DE MORATORIOS
	SELECT
		@MONTO =
		ISNULL((SELECT SUM(SAL_RUBRO) FROM Quiero_Confianza_Shadow.PR.PR_RUBRO_COBRO_X_CREDITO A WHERE 
		A.NUM_CREDITO = @NUM_CREDITO AND A.COD_RUBRO IN ('MORATORIOS', 'INTERES_MORATORIO','MORA_EMPRESARIAL') AND A.IND_ESTADO = 'P' AND dbo.FN_ES_COVID(A.Ind_Posposicion,A.Fecha_Posposicion,A.NUM_CREDITO) != 'S'
