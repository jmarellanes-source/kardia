		@MONTO_OFFSET =
		ISNULL((SELECT SUM(MON_DIARIO) FROM Quiero_Confianza_shadow.PR.PR_CALCULO_MORA_DIA
		WHERE NUM_CREDITO = @NUM_CREDITO
		AND FECHA_CALCULO IN(@FECHA_INICIO_REF, @FECHA_SISTEMA)),0), -- SE EJECUTA CUANDO EL SISTEMA ESTA EN T+1
	
