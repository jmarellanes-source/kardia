		ISNULL((SELECT SUM(SAL_RUBRO) FROM Quiero_Confianza_Shadow.PR.PR_RUBRO_COBRO_X_CREDITO A WHERE 
		A.NUM_CREDITO = @NUM_CREDITO AND A.COD_RUBRO IN ('MORATORIOS', 'INTERES_MORATORIO','MORA_EMPRESARIAL') AND A.IND_ESTADO = 'P' AND dbo.FN_ES_COVID(A.Ind_Posposicion,A.Fecha_Posposicion,A.NUM_CREDITO) = 'S'
		),0)
		
		SET @MONTO = CASE WHEN @MONTO - @MONTO_OFFSET > 0 THEN @MONTO - @MONTO_OFFSET ELSE @MONTO END

	INSERT INTO PO.SAF_MOV_TRASPASO (ID_EXTERNO, NUM_CREDITO, NOM_CLIENTE, ID_FONDEO, ID_PRODUCTO, CONCEPTO_FINAL, RUBRO,
	MONTO, ID_TIPO_CREDITO, TIPO_VIVIENDA, FECHA_MOVIMIENTO, IND_ETAPA, TABLA_ORIGEN, ID_POLIZA, CONCEPTO, COD_CLIENTE,
	IND_ESTADO, TIPO_CREDITO, CANAL)
	SELECT
		@ID_EXTERNO, @NUM_CREDITO, @NOM_CLIENTE, @ID_FONDEO_ACTUAL, @ID_PRODUCTO, 
		CONCAT(@LEYENDA, @ID_EXTERNO, ' ', @NOM_CLIENTE),
		'MORATORIOS', @MONTO, @ID_TIPO_CREDITO, '', @FECHA_INICIO, @IND_ETAPA_ACTUAL,
		'CASTIGO COM', @ID_POLIZA, '','','P', @TIPO_CREDITO, @CANAL

	INSERT INTO PO.SAF_MOV_TRASPASO (ID_EXTERNO, NUM_CREDITO, NOM_CLIENTE, ID_FONDEO, ID_PRODUCTO, CONCEPTO_FINAL, RUBRO,
	MONTO, ID_TIPO_CREDITO, TIPO_VIVIENDA, FECHA_MOVIMIENTO, IND_ETAPA, TABLA_ORIGEN, ID_POLIZA, CONCEPTO, COD_CLIENTE,
	IND_ESTADO, IND_COVID, TIPO_CREDITO, CANAL)
	SELECT 
		@ID_EXTERNO, @NUM_CREDITO, @NOM_CLIENTE, @ID_FONDEO_ACTUAL, @ID_PRODUCTO, 
		CONCAT(@LEYENDA, @ID_EXTERNO, ' ', @NOM_CLIENTE),
		'MORATORIOS', @MON_TRASPASO_COVID, @ID_TIPO_CREDITO, '', @FECHA_INICIO, @IND_ETAPA_ACTUAL,
		'CASTIGO COM', @ID_POLIZA, '','','P','S', @TIPO_CREDITO, @CANAL

	-- # TRASPASO DE IVA MORATORIOS
	SELECT
