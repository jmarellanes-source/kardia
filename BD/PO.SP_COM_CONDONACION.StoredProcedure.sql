                    --print '|@TOTAL:|'+isnull(cast(@TOTAL as varchar),'')+'|@MONTO:|'+isnull(cast(@MONTO as varchar),'')+'|@SUMA89:|'+isnull(cast(@SUMA89 as varchar),'')+'|@ORDEN:|'+isnull(cast(@ORDEN as varchar),'')+'|@BANDERA:|'+isnull(cast(@BANDERA as varchar),'')++'|@rubro:|'+isnull(cast(@RUBRO as varchar),'')+'|@CREDITO:|'+isnull(cast(@NUM_CREDITO as varchar),'')+'|@INI:|'+isnull(cast(@ETAPA_3_INI_1M as varchar),'')
					
